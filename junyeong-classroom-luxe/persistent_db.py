"""PostgreSQL persistence for the existing parameterized classroom SQL.

SQLite remains available for local development. A configured PostgreSQL failure
must never fall back to a new, empty SQLite database.
"""
import os
import re
import sqlite3
from contextlib import contextmanager


def database_url():
    value = os.getenv('CLASSROOM_DATABASE_URL', '').strip() or os.getenv('DATABASE_URL', '').strip()
    if value and not value.startswith(('postgresql://', 'postgres://')):
        raise RuntimeError('CLASSROOM_DATABASE_URL must be a PostgreSQL connection URL')
    return value


class Row:
    """sqlite3.Row-compatible indexing and mapping (including dict(row))."""
    def __init__(self, names, values):
        self.names = names
        self.values = values

    def keys(self):
        return self.names

    def __getitem__(self, key):
        return self.values[key if isinstance(key, int) else self.names.index(key)]

    def __iter__(self):
        return iter(self.values)

    def __len__(self):
        return len(self.values)


class Cursor:
    def __init__(self, cursor=None, rows=None, lastrowid=None):
        self.cursor = cursor
        self.rows = iter(rows) if rows is not None else None
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount if cursor is not None else 0

    def fetchone(self):
        if self.rows is not None:
            return next(self.rows, None)
        values = self.cursor.fetchone()
        if values is None:
            return None
        return Row([c.name for c in self.cursor.description], values)

    def fetchmany(self, size=1):
        result = []
        for _ in range(size):
            row = self.fetchone()
            if row is None:
                break
            result.append(row)
        return result

    def fetchall(self):
        return list(self)

    def __iter__(self):
        while (row := self.fetchone()) is not None:
            yield row


# Only SQL text outside quoted strings/identifiers is rewritten. Values always
# remain driver parameters; a literal '?' in a title or SQL string is untouched.
QUOTED = re.compile(r"('(?:''|[^'])*'|\"(?:\"\"|[^\"])*\")")


def postgres_sql(statement, bound=False):
    sql = statement.strip().rstrip(';')
    ignore = bool(re.match(r'INSERT\s+OR\s+IGNORE\b', sql, re.I))
    replace = re.match(r'INSERT\s+OR\s+REPLACE\s+INTO\s+(railway_backup_sources|r2_backup_sources)\s*\(([^)]+)\)', sql, re.I)
    if re.match(r'INSERT\s+OR\s+REPLACE', sql, re.I) and not replace:
        raise ValueError('Unsupported SQLite replacement statement')
    sql = re.sub(r'\bINSERT\s+OR\s+(?:IGNORE|REPLACE)\b', 'INSERT', sql, flags=re.I)
    pieces = QUOTED.split(sql)
    for index in range(0, len(pieces), 2):
        piece = pieces[index]
        piece = re.sub(r'\bid\s+INTEGER\s+PRIMARY\s+KEY(?:\s+AUTOINCREMENT)?\b',
                       'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', piece, flags=re.I)
        piece = re.sub(r'\bINTEGER\b', 'BIGINT', piece, flags=re.I)
        piece = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', piece, flags=re.I)
        piece = re.sub(r'\bBLOB\b', 'BYTEA', piece, flags=re.I)
        piece = re.sub(r'\bend\b', '"end"', piece)
        pieces[index] = piece.replace('?', '%s')
    sql = ''.join(pieces)
    if ignore:
        sql += ' ON CONFLICT DO NOTHING'
    if replace:
        columns = [c.strip() for c in replace[2].split(',')]
        sql += ' ON CONFLICT(video_id) DO UPDATE SET ' + ','.join(
            f'{c}=excluded.{c}' for c in columns if c != 'video_id')
    # psycopg interprets percent signs when parameters are supplied.
    if bound:
        sql = re.sub(r'%(?!s\b)', '%%', sql)
    return sql


class Connection:
    dialect = 'postgresql'

    def __init__(self, raw, schema):
        self.raw = raw
        self.schema = schema

    def execute(self, statement, params=None):
        sql = statement.strip().rstrip(';')
        pragma = re.fullmatch(r'PRAGMA\s+table_info\((\w+)\)', sql, re.I)
        if pragma:
            result = self.raw.execute('''SELECT ordinal_position-1,column_name,data_type,
                CASE WHEN is_nullable='NO' THEN 1 ELSE 0 END,column_default,0
                FROM information_schema.columns WHERE table_schema=%s AND table_name=%s
                ORDER BY ordinal_position''', (self.schema, pragma[1]))
            names = ['cid', 'name', 'type', 'notnull', 'dflt_value', 'pk']
            return Cursor(rows=[Row(names, tuple(r)) for r in result])
        if re.fullmatch(r'PRAGMA\s+(foreign_keys\s*=\s*ON|journal_mode\s*=\s*WAL)', sql, re.I):
            return Cursor(rows=[])
        if sql.upper().startswith('PRAGMA'):
            raise ValueError('Unsupported database pragma')
        if sql.upper() == 'BEGIN IMMEDIATE':
            # Serialize read/modify/write operations across workers and redeploys.
            self.raw.execute('SELECT pg_advisory_xact_lock(%s)', (71023001 if self.schema == 'classroom' else 71023002,))
            return Cursor(rows=[])
        translated = postgres_sql(sql, params is not None)
        returning = bool(re.match(r'INSERT\s+INTO\s+chunks\b', sql, re.I))
        if returning:
            translated += ' RETURNING id'
        result = self.raw.execute(translated, params)
        if returning:
            return Cursor(rows=[], lastrowid=result.fetchone()[0])
        return Cursor(result)

    def executemany(self, statement, parameters):
        for params in parameters:
            self.execute(statement, params)

    def executescript(self, script):
        # Existing scripts contain no triggers or procedures. complete_statement
        # correctly handles semicolons inside quoted literals.
        current = ''
        for char in script:
            current += char
            if char == ';' and sqlite3.complete_statement(current):
                self.execute(current)
                current = ''
        if current.strip():
            self.execute(current)


@contextmanager
def connect(schema='classroom', initialize=False):
    if schema not in ('classroom', 'lecture_ai'):
        raise ValueError('Unknown database namespace')
    import psycopg
    from psycopg import sql
    # Connection URLs and raw driver errors must never be included in logs.
    try:
        raw = psycopg.connect(database_url(), connect_timeout=15)
    except psycopg.Error:
        raise RuntimeError('Persistent database connection failed; local fallback is disabled') from None
    try:
        with raw.transaction():
            raw.execute('SET LOCAL statement_timeout = 30000')
            raw.execute('SET LOCAL lock_timeout = 15000')
            if initialize:
                raw.execute('SELECT pg_advisory_xact_lock(%s)', (71023001 if schema == 'classroom' else 71023002,))
                raw.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(schema)))
            raw.execute(sql.SQL('SET LOCAL search_path TO {}').format(sql.Identifier(schema)))
            yield Connection(raw, schema)
    finally:
        raw.close()


def persistent_key(local_key=None):
    """Keep the same identity/encryption key through replacement containers."""
    from cryptography.fernet import Fernet
    explicit = os.getenv('CLASSROOM_DATA_KEY', '').encode()
    candidate = explicit or local_key or Fernet.generate_key()
    Fernet(candidate)  # Validate before persisting.
    with connect(initialize=True) as db:
        db.execute('CREATE TABLE IF NOT EXISTS app_secrets(name TEXT PRIMARY KEY,value TEXT NOT NULL)')
        db.execute("INSERT OR IGNORE INTO app_secrets VALUES('identity_key',?)", (candidate.decode(),))
        saved = db.execute("SELECT value FROM app_secrets WHERE name='identity_key'").fetchone()[0].encode()
        if explicit and saved != explicit:
            raise RuntimeError('CLASSROOM_DATA_KEY differs from the existing database key; refusing to change identities')
        return saved
